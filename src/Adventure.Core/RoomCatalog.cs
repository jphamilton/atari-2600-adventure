    private static void Add(
        Room[] rooms,
        int id,
        string name,
        byte color,
        byte control,
        int up,
        int right,
        int down,
        int left,
        byte[] graphic)
    {
        var reflect = (control & 0x01) != 0;
        rooms[id] = new Room(id, name, color, control, up, right, down, left, Playfield.Decode(graphic, reflect));
    }

